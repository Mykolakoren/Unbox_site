import { ruPlural } from './plural';

/**
 * Хвост тоста «Серия создана…» (12.10): срочная встреча серии — меньше 12 ч до
 * начала (в выходные 24 ч) или после 21:00 на утро — у не-админа ждёт
 * подтверждения администратора. Число берём из ответа сервера (pendingApproval),
 * не угадываем на экране.
 */
export function seriesApprovalNote(waiting?: number | null): string {
    const n = waiting ?? 0;
    if (n <= 0) return '';
    if (n === 1) return ' · первая встреча ждёт подтверждения администратора';
    return ` · ${n} ${ruPlural(n, ['встреча ждёт', 'встречи ждут', 'встреч ждут'])} подтверждения администратора`;
}
